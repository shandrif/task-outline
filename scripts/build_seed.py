"""Turn seed/questions.json into seed/seed.sql (positions, sections, items)."""
import json, re, sys

src, out = sys.argv[1], sys.argv[2]
q = lambda s: "'" + s.replace("'", "''") + "'"
lines = ["-- Generated by scripts/build_seed.py from the HM SBS workbook"]
sid = iid = 0
for pid, p in enumerate(json.load(open(src)), 1):
    lines.append(f"INSERT INTO positions (id,name,sort) VALUES ({pid},{q(p['name'])},{pid});")
    for si, s in enumerate(p["sections"], 1):
        sid += 1
        lines.append(f"INSERT INTO sections (id,position_id,title,sort) VALUES ({sid},{pid},{q(s['title'].strip())},{si});")
        for ii, it in enumerate(s["items"], 1):
            iid += 1
            text = re.sub(r"^\s*\d+\s*\.\s*", "", it["text"]).strip() if it["kind"] == "question" else it["text"].strip()
            lines.append(f"INSERT INTO items (id,section_id,kind,text,sort) VALUES ({iid},{sid},{q(it['kind'])},{q(text)},{ii});")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{sid} sections, {iid} items")
